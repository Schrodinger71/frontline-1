const __phLast = {};
function pick(list) { return list[Math.floor(Math.random() * list.length)]; }

function phr(key, args, u) {
  const set = PH[key];
  if (!set) return '';
  let list = (set.all || []).slice();
  if (u && u.trait && set[u.trait]) list = list.concat(set[u.trait], set[u.trait]);
  if (!list.length) return '';
  const memoKey = key + (u ? u.id : '');
  let f;
  if (list.length < 2) f = list[0];
  else { do f = pick(list); while (f === __phLast[memoKey]); }
  __phLast[memoKey] = f;
  return f(args || {});
}

module.exports = { phr, PH };
